package com.peco2282.obfaryn.core.jar

import com.peco2282.obfaryn.core.context.ObfuscationContext
import org.objectweb.asm.ClassWriter
import org.objectweb.asm.util.CheckClassAdapter
import java.nio.file.Files
import java.nio.file.Path
import java.util.jar.JarEntry
import java.util.jar.JarOutputStream


/**
 * Writes transformed classes and resources as a JAR.
 *
 * Classes are emitted before resources; reproducible mode sorts each group and sets entry
 * timestamps to zero. This does not make randomly transformed class bytes deterministic.
 * Obsolete input JAR signature resources are omitted because transforming bytecode invalidates
 * those signatures.
 */
class JarWriter {

  /**
   * Emits [context] to [output].
   *
   * [verifyOutput] validates generated bytecode with ASM. [recomputeFrames] uses [classpath]
   * to resolve external supertypes and fails if a required hierarchy cannot be resolved.
   * Maximum stack/local sizes are always computed; existing frames are retained unless
   * recomputation is requested. The classpath is not consulted when recomputation is disabled.
   *
   * Creates parent directories and truncates an existing output. Writes go directly to [output],
   * not a temporary archive, so a failure can leave partial output. Class/resource path collisions
   * are not resolved and fail when adding the duplicate entry. Signature resources are omitted
   * from the archive without removing them from [context].
   */
  fun write(
    context: ObfuscationContext,
    output: Path,
    reproducible: Boolean = true,
    verifyOutput: Boolean = false,
    recomputeFrames: Boolean = false,
    classpath: List<Path> = emptyList(),
  ) {
    output.parent?.let {
      Files.createDirectories(it)
    }

    ClassHierarchyResolver(context, if (recomputeFrames) classpath else emptyList()).use { hierarchy -> Files.newOutputStream(output).use { fileOutput ->
      JarOutputStream(fileOutput).use { jarOutput ->
        writeClasses(
          context = context,
          output = jarOutput,
          reproducible = reproducible,
          verifyOutput = verifyOutput,
          recomputeFrames = recomputeFrames,
          hierarchy = hierarchy,
        )

        writeResources(
          context = context,
          output = jarOutput,
          reproducible = reproducible,
        )
      }
    } }
  }

  private fun writeClasses(
    context: ObfuscationContext,
    output: JarOutputStream,
    reproducible: Boolean,
    verifyOutput: Boolean,
    recomputeFrames: Boolean,
    hierarchy: ClassHierarchyResolver,
  ) {
    (if (reproducible) context.classes.values.sortedBy { it.name } else context.classes.values).forEach { classNode ->
      val writer = object : ClassWriter(if (recomputeFrames) COMPUTE_FRAMES or COMPUTE_MAXS else COMPUTE_MAXS) {
        override fun getCommonSuperClass(type1: String, type2: String): String = hierarchy.commonSuperClass(type1, type2)
      }

      try {
        if (verifyOutput) classNode.accept(CheckClassAdapter(writer, true)) else classNode.accept(writer)
      } catch (cause: Exception) {
        throw IllegalStateException("Failed writing class ${classNode.name} (frame computation: $recomputeFrames)", cause)
      }

      val entry = JarEntry(
        "${classNode.name}.class",
      )
      if (reproducible) entry.time = 0

      output.putNextEntry(entry)
      output.write(writer.toByteArray())
      output.closeEntry()
    }
  }

  private fun writeResources(
    context: ObfuscationContext,
    output: JarOutputStream,
    reproducible: Boolean,
  ) {
    (if (reproducible) context.resources.values.sortedBy { it.name } else context.resources.values).forEach { resource ->
      if (Regex("(?i)^META-INF/[^/]+\\.(SF|RSA|DSA|EC)$").matches(resource.name)) return@forEach
      val entry = JarEntry(resource.name)
      if (reproducible) entry.time = 0

      output.putNextEntry(entry)
      output.write(resource.data)
      output.closeEntry()
    }
  }
}
